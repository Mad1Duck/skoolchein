/** "voteForCandidate" -> "Vote for candidate", for any function not in the table. */
const humanize = (fn: string) => {
  const s = fn.replace(/([a-z0-9])([A-Z])/g, "$1 $2").toLowerCase();
  return s.charAt(0).toUpperCase() + s.slice(1);
};

export const txLabel = (fn: string, lang: Lang) => (lang === "id" ? ID : EN)[fn] ?? humanize(fn);
